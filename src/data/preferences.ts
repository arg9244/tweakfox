export type PresetType = 'balanced' | 'privacy' | 'performance' | 'hardened';

export const presets: Record<PresetType, { name: string; description: string; selections: Record<string, boolean> }> = {
  balanced: {
    name: 'Balanced',
    description: 'Recommended settings for everyday browsing. Good privacy without site breakage.',
    selections: {},
  },
  privacy: {
    name: 'Privacy Focused',
    description: 'Maximum privacy with minimal site breakage. Disables telemetry and tracking.',
    selections: {},
  },
  performance: {
    name: 'Performance',
    description: 'Optimized for speed. All performance tweaks enabled.',
    selections: {},
  },
  hardened: {
    name: 'Hardened',
    description: 'Maximum security. May cause significant site breakage. For advanced users only.',
    selections: {},
  },
};

// Generate preset selections
function generatePresetSelections() {
  // Balanced: all recommended, low risk
  categories.forEach(cat => {
    cat.preferences.forEach(pref => {
      if (pref.recommended && pref.risk === 'low') {
        presets.balanced.selections[pref.id] = true;
      }
    });
  });

  // Privacy: balanced + medium risk privacy items
  Object.assign(presets.privacy.selections, presets.balanced.selections);
  categories.forEach(cat => {
    cat.preferences.forEach(pref => {
      if (pref.recommended && pref.risk === 'medium') {
        presets.privacy.selections[pref.id] = true;
      }
    });
  });

  // Performance: all fastfox + low risk
  const fastfoxCat = categories.find(c => c.id === 'fastfox');
  if (fastfoxCat) {
    fastfoxCat.preferences.forEach(pref => {
      presets.performance.selections[pref.id] = true;
    });
  }
  categories.forEach(cat => {
    if (cat.id !== 'fastfox') {
      cat.preferences.forEach(pref => {
        if (pref.recommended && pref.risk === 'low') {
          presets.performance.selections[pref.id] = true;
        }
      });
    }
  });

  // Hardened: everything
  categories.forEach(cat => {
    cat.preferences.forEach(pref => {
      presets.hardened.selections[pref.id] = true;
    });
  });
}

generatePresetSelections();
